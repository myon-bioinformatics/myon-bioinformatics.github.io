"""Exercise the published knowledge-flow module with Node."""
import ast
import shutil
import subprocess
import tempfile
import unittest
from pathlib import Path


@unittest.skipUnless(shutil.which("node"), "Node required")
class KnowledgeFlowTest(unittest.TestCase):
    def check_module(self, check):
        source = Path(__file__).resolve().parents[1] / "scripts/project_pages.py"
        tree = ast.parse(source.read_text(encoding="utf-8"))
        value = next(
            ast.literal_eval(node.value)
            for node in tree.body
            if isinstance(node, ast.Assign)
            and any(isinstance(target, ast.Name) and target.id == "KNOWLEDGE_FLOW_SOURCE"
                    for target in node.targets)
        )
        fixture = Path(__file__).parent / "fixtures" / "onto_knowledge_flow.json"
        with tempfile.TemporaryDirectory() as tmp:
            folder = Path(tmp)
            (folder / "knowledge.mjs").write_text(value, encoding="utf-8")
            (folder / "check.mjs").write_text(check, encoding="utf-8")
            subprocess.run(["node", "check.mjs", str(fixture.resolve())], cwd=tmp, check=True)

    def test_diffusion(self):
        self.check_module(r"""
import {knowledgeStep, parseGraph, seededIndex} from './knowledge.mjs';
import assert from 'node:assert/strict';

const graph = parseGraph('@prefix ex: <urn:example:> .\r\nex:A ex:r ex:B .\r\nex:B ex:r ex:C .');
assert.equal(graph.nodes.length, 3);
assert.deepEqual(graph.edges, [[0,1], [1,2]]);
let values = [1, 0, 0];
assert.deepEqual(knowledgeStep(values, 0, graph.edges), values);
assert.deepEqual(knowledgeStep(values, 1, graph.edges), [.5, .5, 0]);
for (let i = 0; i < 100; i++) {
  values = knowledgeStep(values, 1, graph.edges);
  assert.ok(values.every(value => value >= 0));
  assert.ok(Math.abs(values.reduce((sum, value) => sum + value, 0) - 1) < 1e-12);
}
assert.throws(() => knowledgeStep(values, 2, graph.edges), RangeError);
assert.equal(seededIndex(123, 3), seededIndex(123, 3));
assert.equal(parseGraph('<urn:a> <urn:r> <urn:a> .').relations.length, 1);
""")

    def test_onto_export(self):
        # Fixture generated by ONTO's export --format ttl path, then read_graph / graph_json.
        self.check_module(r"""
import {knowledgeStep, parseGraph} from './knowledge.mjs';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';

const data = JSON.parse(readFileSync(process.argv[2], 'utf8'));
const graph = parseGraph(JSON.stringify(data));
assert.deepEqual(graph.nodes, ['urn:example:A', 'urn:example:B', 'urn:example:C', 'urn:example:D']);
assert.deepEqual(graph.edges, [[0,1], [0,2]]);
assert.deepEqual(graph.relations.map(({source, target}) => [source, target]), [[0,1], [0,2], [1,0], [2,2]]);
assert.deepEqual(graph.initial, [4, 0, 0, 0]);
assert.deepEqual(graph.confidence, [.75, null, null, null]);
assert.deepEqual(graph.attributes[0].map(({numeric}) => numeric), [null, null, 12.5]);
assert.equal(graph.attributes[0][0].term, '"概念A"@ja');
assert.match(graph.attributes[0][1].term, /二行の\nノート/);
assert.equal(graph.attributes[3][0].numeric, -2);
assert.deepEqual(knowledgeStep(graph.initial, .5, graph.edges), [2, 1, 1, 0]);
assert.deepEqual(graph.confidence, [.75, null, null, null]);
data.rels[0].end.id = '_:blank';
assert.throws(() => parseGraph(JSON.stringify(data)), /JSON文 1.*関係が不正/);
""")

    def test_rejects_unsupported_or_invalid_input(self):
        self.check_module(r"""
import {parseGraph} from './knowledge.mjs';
import assert from 'node:assert/strict';

assert.throws(() => parseGraph('ex:A ex:r ex:B .'), /1行目.*未定義/);
assert.throws(
  () => parseGraph('<urn:a> <urn:r> <urn:b> .\n<urn:a> <urn:r> [ <urn:p> 1 ] .'),
  /2行目.*未対応のTTL構文/
);
assert.throws(() => parseGraph('<urn:a> <urn:knowledge-flow:confidence> 1.01 .'), /範囲外/);
assert.throws(() => parseGraph('<urn:a> <urn:knowledge-flow:activity> -1 .'), /範囲外/);
assert.throws(() => parseGraph('<urn:a> <urn:knowledge-flow:activity> <urn:b> .'), /未対応のRDF項/);
assert.throws(
  () => parseGraph('<urn:a> <urn:knowledge-flow:activity> 0 .\n<urn:a> <urn:knowledge-flow:activity> 2 .'),
  /重複/
);
assert.equal(parseGraph('@prefix : <urn:example:> .\n:A :score 2.5e1 .').attributes[0][0].numeric, 25);
""")
